#!/usr/bin/env python3
"""Generates src/render/spaces.data.js from the original prefabs/spaces/*.tscn.
Usage: python3 tools/gen-spaces.py <path to Rhythia client>
Each space becomes { ext, sub, nodes }: ext = external resources (path), sub = sub-resources (type + properties),
nodes = scene nodes in file order (name, type, parent, properties). Values keep Godot's meaning:
Transform3D(...) -> 12 numbers (basis rows, origin), Color/Vector -> arrays, SubResource/ExtResource -> {sub}/{ext}.
ArrayMesh surfaces are decoded to positions + indices (format version 2, compressed or not)."""
import sys, re, json, base64, struct, os

SPACES = ['grid', 'squircles', 'galaxy', 'tunnel', 'circulartunnel', 'tritunnel', 'vortex', 'relic', 'conspiracy']

def split_args(s):
    out, depth, cur, q = [], 0, '', False
    for ch in s:
        if ch == '"' : q = not q
        if not q and ch in '([{': depth += 1
        if not q and ch in ')]}': depth -= 1
        if ch == ',' and depth == 0 and not q: out.append(cur.strip()); cur = ''
        else: cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

def val(s):
    s = s.strip()
    if s in ('true', 'false'): return s == 'true'
    if s == 'null': return None
    if re.fullmatch(r'-?\d+', s): return int(s)
    if re.fullmatch(r'-?[\d.]+(e-?\d+)?', s): return float(s)
    if s.startswith('"'): return json.loads(s)
    m = re.fullmatch(r'(\w+)\((.*)\)', s, re.S)
    if m:
        t, a = m.group(1), m.group(2)
        if t == 'SubResource': return {'sub': json.loads(a)}
        if t == 'ExtResource': return {'ext': json.loads(a)}
        if t == 'NodePath': return {'path': json.loads(a)}
        if t in ('PackedByteArray',): return {'bytes': json.loads(a) if a else ''}
        if t == 'AABB': return [float(x) for x in split_args(a)]
        return [val(x) for x in split_args(a)]
    if s.startswith('['): return [val(x) for x in split_args(s[1:-1])]
    if s.startswith('{'):
        d = {}
        for kv in split_args(s[1:-1]):
            k, v = kv.split(':', 1); d[json.loads(k.strip())] = val(v)
        return d
    return s

def parse(path):
    txt = open(path).read()
    ext, sub, nodes = {}, {}, []
    for block in re.split(r'\n(?=\[)', txt):
        head, _, body = block.partition('\n')
        props = {}
        # properties: key = value, values may span lines (arrays / dicts)
        key, buf, depth = None, '', 0
        for line in body.split('\n'):
            if key is None:
                m = re.match(r'([\w/]+) = (.*)', line)
                if not m: continue
                key, buf = m.group(1), m.group(2)
            else: buf += '\n' + line
            depth = sum(buf.count(c) for c in '([{') - sum(buf.count(c) for c in ')]}')
            if depth == 0: props[key] = val(buf); key = None
        h = dict(re.findall(r'(\w+)="([^"]*)"', head))
        if head.startswith('[ext_resource'): ext[h['id']] = h['path']
        elif head.startswith('[sub_resource'): sub[h['id']] = {'type': h['type'], **props}
        elif head.startswith('[node'): nodes.append({'name': h['name'], 'type': h.get('type'), 'parent': h.get('parent'), **props})
    return ext, sub, nodes

def decode_surface(s):
    """Godot 4 mesh format version 2: vertex buffer = position (+ normal/tangent); compressed positions are
    u16 x 4 normalised to the AABB. Index buffer u16 (u32 when vertex_count > 65535)."""
    fmt = s['format']; vc = s['vertex_count']; compressed = bool(fmt & (1 << 29))
    vd = base64.b64decode(s['vertex_data']['bytes']); aabb = s['aabb']
    pos = []
    # positions are one contiguous block (12 bytes each, 8 when compressed); normals/tangents follow it
    if compressed:
        stride = 8
        for i in range(vc):
            x, y, z, _ = struct.unpack_from('<4H', vd, i * stride)
            pos += [aabb[0] + x / 65535 * aabb[3], aabb[1] + y / 65535 * aabb[4], aabb[2] + z / 65535 * aabb[5]]
    else:
        stride = 12
        for i in range(vc): pos += list(struct.unpack_from('<3f', vd, i * stride))
    idx = []
    if 'index_data' in s:
        idata = base64.b64decode(s['index_data']['bytes'])
        idx = list(struct.unpack('<%dH' % (len(idata) // 2), idata)) if vc <= 65535 else list(struct.unpack('<%dI' % (len(idata) // 4), idata))
    return {'positions': [round(v, 6) for v in pos], 'indices': idx, 'material': s.get('material')}

def main(root):
    out = {}
    for name in SPACES:
        ext, sub, nodes = parse(os.path.join(root, 'prefabs/spaces', name + '.tscn'))
        for k, r in sub.items():
            if r['type'] == 'ArrayMesh':
                r['surfaces'] = [decode_surface(s) for s in r.pop('_surfaces')]
                r.pop('shadow_mesh', None)
        out[name] = {'ext': ext, 'sub': sub, 'nodes': nodes}
    js = '// Generated by tools/gen-spaces.py from prefabs/spaces/*.tscn. Do not edit.\nexport const SPACES = ' + json.dumps(out, separators=(',', ':')) + ';\n'
    open(os.path.join(os.path.dirname(__file__), '..', 'src/render/spaces.data.js'), 'w').write(js)
    print('wrote', len(js), 'bytes')

main(sys.argv[1])
