# Regenerates src/settings.defs.js from the original SettingsProfile.cs (path as first argument).
import re,json,sys
s=open(sys.argv[1],encoding='utf-8-sig').read()
order=[m.group(1) for m in re.finditer(r'\[Order\][^;{]*?public SettingsItem<\w+> (\w+) \{ get; private set; \}',s)]
decl=dict((m.group(2),m.group(1)) for m in re.finditer(r'public SettingsItem<(\w+)> (\w+) \{ get; private set; \}',s))
init=s[s.index('public SettingsProfile()'):]
items={}
for m in re.finditer(r'\n        (\w+) = new\(([^)]*)\)\s*\{',init):
    name=m.group(1); i=m.end(); d=1
    while d:
        c=init[i]; d+=(c=='{')-(c=='}'); i+=1
    body=init[m.end():i-1]
    g=lambda k:(re.search(k+r' = "((?:[^"\\]|\\.)*)"',body) or [None,None])[1]
    sec=re.search(r'Section = SettingsSection\.(\w+)',body)
    sl=re.search(r'Slider = new\(\)\s*\{([^}]*)\}',body)
    slider=None
    if sl: slider={k:float(v) for k,v in re.findall(r'(Step|MinValue|MaxValue) = ([-\d.]+)f?',sl.group(1))}
    raw=m.group(2).strip()
    items[name]=dict(t=decl[name],d=raw,f=raw.endswith('f') and not raw.startswith('"'),title=g('Title'),desc=g('Description'),section=sec.group(1),slider=slider)
print('ordered',len(order),'skipped (unparsed):',[n for n in order if n not in items])
ui={'Gameplay':['Sensitivity','CursorDrift','ApproachRate','ApproachDistance','FadeIn','FadeOut','Pushback','CameraParallax','FoV'],
 'Visual':['NoteOpacity','NoteOpacityExponent','NoteSize','GridGuides','CursorScale','CursorOpacity','CursorRotation','HPLerpValue','HitPopups','MissPopups'],
 'Audio':['AutoplayJukebox','LocalOffset','AlwaysPlayHitSound','EnableHitSound','EnableMissSound','EnableMenuMusic','VolumeMaster','VolumeMusic','VolumeSFX','VolumeHitSound','VolumeMissSound','VolumeMenuMusic'],
 'Other':['DisplayFPS','ResetToDefaults']}
shown=set(x for v in ui.values() for x in v)
out=[]
for n in [n for n in order if n in items]:
    it=items[n]
    if (it['t']=='Variant' and n!='ResetToDefaults') or n=='SetUserFolderPath': continue
    r=it['d']
    v = r if r in('true','false') or r.startswith('"') else ('0' if r=='default' else ('f(%s)'%r[:-1] if it['f'] else r))
    if r.startswith('Constants'): v='""'
    sl=it['slider']
    out.append("  { id: %s, type: %s, def: %s, title: %s, desc: %s, section: %s%s%s },"%(json.dumps(n),json.dumps(it['t']),v,json.dumps(it['title']),json.dumps(it['desc']),json.dumps(it['section']),
      (", slider: { step: f(%s), min: f(%s), max: f(%s) }"%(sl['Step'],sl['MinValue'],sl['MaxValue'])) if sl else '', ', ui: true' if n in shown else ''))
open('src/settings.defs.js','w').write("""// Generated by tools/gen-settings-defs.py from scripts/database/settings/SettingsProfile.cs: ids, titles, descriptions, defaults, slider
// ranges, sections, in the declaration order the settings menu uses ([Order] = source line). f() = C# float literal (0.05f is stored as a
// double with float32 precision). ui: true = shown in this port's settings menu (the setting drives something that exists here).
// Variant import/file-dialog items and AntiAliasing are left out.
const f = Math.fround;
export const SECTIONS = ['Gameplay', 'Visual', 'Audio', 'Video', 'Other'];   // SettingsSection (None is skipped)
export const DEFS = [
%s
];
"""%"\n".join(out))
print(len(out),'defs;',sum('ui: true' in l for l in out),'shown')
